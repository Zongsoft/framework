using System;
using System.IO;
using System.Threading.Tasks;

using Xunit;

using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;

namespace Zongsoft.Plugins.Tests;

//成功关闭工作台会退出进程，使用同一测试程序的独立入口隔离该行为。
internal static class TestProgram
{
	public static async Task<int> Main(string[] args)
	{
		if(args.Length != 3 || args[0] != "--plugin-probe")
			return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);

		var directory = args[2];
		var trace = Path.Combine(directory, "lifecycle.txt");

		try
		{
			if(args[1] == "registration")
			{
				using var host = Hosting.Application.Daemon(typeof(TestProgram).Assembly.GetName().Name, [$"--contentRoot={directory}"], builder =>
				{
					builder.Environment.EnvironmentName = "Development";
					builder.Configuration["Fixture:registration:enabled"] = "true";
				});
				var snapshot = Assert.Single(host.Services.GetServices<ApplicationLifecycleTests.RegistrationSnapshot>());

				Assert.Equal("http://*:4317/opentelemetry", snapshot.Url);
				Assert.Equal("grpc+http2", snapshot.Protocols);
				File.AppendAllLines(trace, ["registered"]);
				return 0;
			}

			if(args[1] == "terminal")
			{
				using var host = Hosting.Application.Terminal(typeof(TestProgram).Assembly.GetName().Name, [$"--contentRoot={directory}"], builder => builder.Environment.EnvironmentName = "Development");
				var context = host.Services.GetRequiredService<PluginApplicationContext>();
				Assert.Equal("Terminal", context.ApplicationType);
				Assert.Same(context, host.Services.GetRequiredService<Services.IApplicationContext>());
				Assert.Equal(WorkbenchStatus.None, context.Workbench.Status);
				Assert.Same(host.Services.GetRequiredService<ApplicationLifecycleTests.ProbeService>(), context.PluginTree.Find("/Workspace/Environment/Services/FixtureService").UnwrapValue(ObtainMode.Never));
				File.AppendAllLines(trace, ["created"]);
				return 0;
			}

			if(args[1] == "web")
			{
				await using var app = Zongsoft.Web.Application.Web(typeof(TestProgram).Assembly.GetName().Name, [$"--contentRoot={directory}"], builder => builder.Environment.EnvironmentName = "Development");
				var context = app.Services.GetRequiredService<Zongsoft.Web.WebApplicationContext>();
				Assert.Same(context, app.Services.GetRequiredService<PluginApplicationContext>());
				Assert.Same(context, app.Services.GetRequiredService<Services.IApplicationContext>());
				Assert.False(context.Initialize());
				Assert.Equal(WorkbenchStatus.None, context.Workbench.Status);
				Assert.IsType<Zongsoft.Web.ControllerActivator>(app.Services.GetRequiredService<Microsoft.AspNetCore.Mvc.Controllers.IControllerActivator>());
				Assert.Same(app.Services.GetRequiredService<ApplicationLifecycleTests.ProbeService>(), context.PluginTree.Find("/Workspace/Environment/Services/FixtureService").UnwrapValue(ObtainMode.Never));
				File.AppendAllLines(trace, ["created"]);
				return 0;
			}

			if(args[1] == "daemon")
			{
				using var host = Hosting.Application.Daemon(typeof(TestProgram).Assembly.GetName().Name, [$"--contentRoot={directory}"], builder =>
				{
					builder.Environment.ContentRootPath = directory;
					builder.Environment.EnvironmentName = "Development";
				});
				var context = host.Services.GetRequiredService<PluginApplicationContext>();
				Assert.Equal("Daemon", context.ApplicationType);
				Assert.Same(context, host.Services.GetRequiredService<Services.IApplicationContext>());
				Assert.False(context.Initialize());
				Assert.Same(context, context.PluginTree.Find("/Workspace/Environment/ApplicationContext").Value);
				Assert.Equal(WorkbenchStatus.None, context.Workbench.Status);
				context.Workbench.Opened += (_, _) => File.AppendAllLines(trace, ["opened"]);
				context.Workbench.Closed += (_, _) => File.AppendAllLines(trace, ["closed"]);

				await host.StartAsync();

				Assert.Equal(WorkbenchStatus.Running, context.Workbench.Status);
				File.AppendAllLines(trace, ["started"]);
				await host.StopAsync();
				return 2;
			}

			using var configuration = new ConfigurationManager();
			var services = new ServiceCollection();
			services.AddSingleton<IConfiguration>(configuration);
			var provider = new Services.ServiceProviderFactory().CreateServiceProvider(services);
			using var application = new ProbeApplicationContext(provider, new PluginOptions(configuration, directory, "Development"));
			Assert.True(application.Initialize());
			var workbench = Assert.IsType<ProbeWorkbench>(application.Workbench);
			workbench.Opening += (_, _) => File.AppendAllLines(trace, [$"opening:{workbench.Status}"]);
			workbench.Opened += (_, _) => File.AppendAllLines(trace, [$"opened:{workbench.Status}"]);
			workbench.Closing += (_, _) => File.AppendAllLines(trace, [$"closing:{workbench.Status}"]);
			workbench.Closed += (_, _) => File.AppendAllLines(trace, [$"closed:{workbench.Status}"]);

			workbench.Open();
			workbench.Open();
			Assert.Equal(WorkbenchStatus.Running, workbench.Status);
			workbench.Close();
			return 2;
		}
		catch(Exception error)
		{
			File.AppendAllText(trace, error.ToString());
			return 1;
		}
	}

	private sealed class ProbeApplicationContext(IServiceProvider services, PluginOptions options) : PluginApplicationContext(services, options)
	{
		protected override IWorkbenchBase CreateWorkbench(out PluginTreeNode node) => base.CreateWorkbench(out node) ?? new ProbeWorkbench(this);
	}

	private sealed class ProbeWorkbench(PluginApplicationContext application) : WorkbenchBase(application);
}
