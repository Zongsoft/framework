using System;
using System.IO;
using System.Text;
using System.Threading.Tasks;

namespace Zongsoft.Plugins.Web.IntegrationTests;

internal static class TestProgram
{
	public static async Task<int> Main(string[] args)
	{
		if(args.Length != 4 || args[0] != "--endpoint-probe")
			return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);

		try
		{
			Console.OutputEncoding = new UTF8Encoding(false);
			using var scope = new EndpointTestScope(args[2]);
			await EndpointScenarios.RunAsync(args[1], scope, args[3]);
			File.WriteAllText(Path.Combine(scope.DirectoryPath, "completed.txt"), args[1]);
			return 0;
		}
		catch(Exception error)
		{
			Console.Error.WriteLine(error);
			return 1;
		}
	}
}
