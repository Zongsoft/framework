using System;
using System.Threading.Tasks;

using Xunit;

namespace Zongsoft.Messaging.ZeroMQ.Tests;

//插件上下文和 Main 插件含有进程级状态，使用独立入口隔离每次插件装配验证。
internal static class TestProgram
{
	public static bool IsPluginProbe { get; private set; }

	public static async Task<int> Main(string[] args)
	{
		if(args.Length != 2 || args[0] != "--zeromq-plugin-probe")
			return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);

		try
		{
			Assert.True(Global.IsTestingEnabled);
			IsPluginProbe = true;
			var tests = new ZeroPluginTests();

			switch(args[1])
			{
				case nameof(ZeroPluginTests.DaemonPluginLoadsEnabledWorkerAndExchangesMessages):
					await tests.DaemonPluginLoadsEnabledWorkerAndExchangesMessages();
					break;
				case nameof(ZeroPluginTests.DisabledDaemonPluginDoesNotStartListener):
					await tests.DisabledDaemonPluginDoesNotStartListener();
					break;
				case nameof(ZeroPluginTests.ClientPluginDoesNotCreateServer):
					await tests.ClientPluginDoesNotCreateServer();
					break;
				default:
					return 2;
			}

			Console.WriteLine($"Completed:{args[1]}");
			return 0;
		}
		catch(Exception exception)
		{
			Console.Error.WriteLine(exception);
			return 1;
		}
	}
}
