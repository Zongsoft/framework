using System;
using System.IO;
using System.Runtime.ExceptionServices;
using System.Text;
using System.Threading;
using System.Threading.Tasks;

using Xunit;

namespace Zongsoft.Terminals.IntegrationTests;

internal static class TestProgram
{
	private static readonly TimeSpan _timeout = TimeSpan.FromSeconds(10);

	public static async Task<int> Main(string[] args)
	{
		if(args.Length == 2 && args[0] == "--shell-child")
			return await ShellProcess.RunChildAsync(args[1]);

		if(args.Length != 2 || args[0] != "--terminal-input")
			return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);

		Console.InputEncoding = new UTF8Encoding(false);
		Console.OutputEncoding = new UTF8Encoding(false);

		try
		{
			await RunAsync(args[1]);
			Console.WriteLine("PASS");
			return 0;
		}
		catch(Exception exception)
		{
			Console.Error.WriteLine(exception);
			return 1;
		}
	}

	private static async Task RunAsync(string scenario)
	{
		if(scenario is "controlled-line" or "controlled-fault")
		{
			await VerifyControlledInputAsync(scenario == "controlled-fault");
			return;
		}

		var input = Terminal.Console.Input;

		switch(scenario)
		{
			case "exit":
				await CancelWaitAsync(input);
				input.Dispose();
				break;
			case "resume":
				for(var index = 0; index < 4; index++)
					await CancelWaitAsync(input);

				var pending = input.ReadLineAsync();
				Assert.False(pending.IsCompleted);
				await Assert.ThrowsAsync<InvalidOperationException>(() => input.ReadLineAsync());

				Write("resumed\nnext\n");

				Assert.Equal("resumed", await pending.WaitAsync(_timeout));
				Assert.Equal("next", await input.ReadLineAsync().WaitAsync(_timeout));
				break;
			case "shared":
				Assert.Same(input, Terminal.Console.Input);

				Terminal.Console.Input = TextReader.Null;
				Assert.Same(TextReader.Null, Terminal.Console.Input);

				Terminal.Console.Input = null;

				Assert.Same(input, Terminal.Console.Input);
				Assert.Throws<NotSupportedException>(() => input.Read());
				Assert.Throws<NotSupportedException>(() => input.Peek());
				Assert.Throws<NotSupportedException>(() => input.ReadLine());

				var reading = input.ReadLineAsync();
				input.Dispose();
				input.Close();

				Assert.False(reading.IsCompleted);
				Assert.Same(input, Terminal.Console.Input);
				Assert.Throws<NotSupportedException>(() => input.ReadLine());

				Write("current\nafter-disposal\n");

				Assert.Equal("current", await reading.WaitAsync(_timeout));
				Assert.Equal("after-disposal", await input.ReadLineAsync().WaitAsync(_timeout));
				break;
			case "text":
				Write("中文🙂\r\n\nfinal");
				Console.WriteLine("EOF");

				Assert.Equal("中文🙂", await input.ReadLineAsync().WaitAsync(_timeout));
				Assert.Equal(string.Empty, await input.ReadLineAsync().WaitAsync(_timeout));
				Assert.Equal("final", await input.ReadLineAsync().WaitAsync(_timeout));
				Assert.Null(await input.ReadLineAsync().WaitAsync(_timeout));
				Assert.Null(await input.ReadLineAsync().WaitAsync(_timeout));
				break;
			default:
				throw new ArgumentOutOfRangeException(nameof(scenario));
		}
	}

	private static async Task CancelWaitAsync(TextReader input)
	{
		using var cancellation = new CancellationTokenSource();
		var reading = input.ReadLineAsync(cancellation.Token).AsTask();
		Assert.False(reading.IsCompleted);

		cancellation.Cancel();

		await Assert.ThrowsAnyAsync<OperationCanceledException>(() => reading.WaitAsync(_timeout));
	}

	private static async Task VerifyControlledInputAsync(bool fail)
	{
		var source = new ControlledReader();
		Console.SetIn(source);
		var input = Terminal.Console.Input;
		Assert.Throws<NotSupportedException>(() => input.ReadLine());
		Assert.Equal(0, source.ReadCount);

		using(var cancellation = new CancellationTokenSource())
		{
			var reading = input.ReadLineAsync(cancellation.Token).AsTask();
			await source.Started.Task.WaitAsync(_timeout);

			Assert.Equal(1, source.ReadCount);
			Assert.Throws<NotSupportedException>(() => input.ReadLine());
			await Assert.ThrowsAsync<InvalidOperationException>(() => input.ReadLineAsync());

			cancellation.Cancel();

			await Assert.ThrowsAnyAsync<OperationCanceledException>(() => reading.WaitAsync(_timeout));
		}

		for(var index = 0; index < 4; index++)
			await CancelWaitAsync(input);

		Assert.Equal(1, source.ReadCount);

		if(fail)
		{
			var failure = new IOException("Controlled input failure.");
			source.Fail(failure);
			await source.Returned.Task.WaitAsync(_timeout);

			Assert.Throws<NotSupportedException>(() => input.ReadLine());
			Assert.Same(failure, await Assert.ThrowsAsync<IOException>(() => input.ReadLineAsync().WaitAsync(_timeout)));
			Assert.Throws<NotSupportedException>(() => input.ReadLine());
			Assert.Same(failure, await Assert.ThrowsAsync<IOException>(() => input.ReadLineAsync(CancellationToken.None).AsTask().WaitAsync(_timeout)));
			Assert.Equal(1, source.ReadCount);
		}
		else
		{
			source.Complete("retained");
			await source.Returned.Task.WaitAsync(_timeout);

			Assert.Throws<NotSupportedException>(() => input.ReadLine());
			Assert.Equal(1, source.ReadCount);
			Assert.Equal("retained", await input.ReadLineAsync().WaitAsync(_timeout));
			Assert.Equal(1, source.ReadCount);

			Assert.Throws<NotSupportedException>(() => input.ReadLine());
			Assert.Equal(1, source.ReadCount);
			Assert.Equal("second", await input.ReadLineAsync(CancellationToken.None).AsTask().WaitAsync(_timeout));
			Assert.Equal(2, source.ReadCount);

			Assert.Null(await input.ReadLineAsync(CancellationToken.None).AsTask().WaitAsync(_timeout));
			Assert.Null(await input.ReadLineAsync().WaitAsync(_timeout));
			Assert.Throws<NotSupportedException>(() => input.ReadLine());
			Assert.Equal(3, source.ReadCount);
		}
	}

	private static void Write(string text) => Console.WriteLine("WRITE:" + Convert.ToBase64String(Encoding.UTF8.GetBytes(text)));

	private sealed class ControlledReader : TextReader
	{
		private int _readCount;
		private readonly ManualResetEventSlim _completion = new();
		private string _result;
		private ExceptionDispatchInfo _failure;
		public readonly TaskCompletionSource Started = new(TaskCreationOptions.RunContinuationsAsynchronously);
		public readonly TaskCompletionSource Returned = new(TaskCreationOptions.RunContinuationsAsynchronously);

		public int ReadCount => Volatile.Read(ref _readCount);

		public void Complete(string result)
		{
			_result = result;
			_completion.Set();
		}

		public void Fail(Exception failure)
		{
			_failure = ExceptionDispatchInfo.Capture(failure);
			_completion.Set();
		}

		public override string ReadLine()
		{
			var count = Interlocked.Increment(ref _readCount);
			if(count > 1)
				return count == 2 ? "second" : null;

			this.Started.TrySetResult();

			//仅模拟后台读取线程面对的原生同步输入；公共终端输入必须使用异步入口。
			try
			{
				_completion.Wait();
				_failure?.Throw();
				return _result;
			}
			finally { this.Returned.TrySetResult(); }
		}
	}
}
