using System;
using System.Collections.Generic;

namespace Zongsoft.Collections;

public static class ListUtility
{
	public static SynchronizedList<T> Synchronize<T>(this IList<T> list)
	{
		if(list == null)
			return null;

		return list as SynchronizedList<T> ?? new(list);
	}
}
