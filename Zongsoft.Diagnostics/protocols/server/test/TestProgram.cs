using System;
using System.IO;
using System.Text;
using System.Threading.Tasks;

namespace Zongsoft.Diagnostics.Protocols.Server.Tests;

internal static class TestProgram
{
	public static async Task<int> Main(string[] args)
	{
		if(args.Length != 3 || args[0] != "--otlp-probe")
			return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);

		try
		{
			Console.OutputEncoding = new UTF8Encoding(false);
			await OtlpScenarios.RunAsync(args[1], args[2]);
			File.WriteAllText(Path.Combine(args[2], "completed.txt"), args[1]);
			return 0;
		}
		catch(Exception exception)
		{
			Console.Error.WriteLine(exception);
			return 1;
		}
	}
}
